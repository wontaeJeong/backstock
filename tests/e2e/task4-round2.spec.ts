import { expect, test } from "@playwright/test"

test("R1 미완성 분기 사이 다중 편집이 실행·저장·실험의 같은 정의에 남는다",async({page},info)=>{
  const definition={schema_version:"1",name:"다중 분기 복구 회귀",universe:["NASDAQ:AAPL"],timeframe:"1m",entry:{condition:{op:"not",condition:{op:"lt",left:{type:"bar_field",field:"close",shift:0},right:{type:"constant",value:"0.000000000001"}}}},position_sizing:{method:"fixed_notional",notional:"500.00000001"},risk:{stop_loss:{mode:"percent",value:"3",atr_period:14},take_profit:{mode:"percent",value:"12.000000000001",atr_period:17},trailing_stop:null,max_holding_bars:null},session:{entry_start:"09:30",entry_end:"15:00",flatten_at:"15:50",weekdays:[0,1,2,3,4]},order:{order_type:"market",time_in_force:"day",limit_offset_bps:null,stop_offset_bps:null}}
  await page.goto("/")
  await page.getByLabel("데이터 출처").selectOption("demo")
  await page.locator("summary").filter({hasText:"전략 JSON 편집·가져오기"}).click()
  await page.getByLabel("전략 JSON 가져오기").setInputFiles({name:"cross-branch.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(definition))})
  await expect(page.getByText("JSON 가져오기 완료 · 전체 조건 보존",{exact:true})).toBeVisible()
  await page.locator("summary").filter({hasText:"03 · 손절·익절·보유 기간"}).click()
  await page.locator("summary").filter({hasText:"주문·세션·spread"}).click()
  const simulationRequests:unknown[]=[]
  page.on("request",r=>{if(r.method()==="POST" && r.url().endsWith("/api/research/simulations"))simulationRequests.push(r.postDataJSON())})
  await page.getByLabel("고정 투자 금액 (USD)",{exact:true}).fill("")
  await page.getByLabel("손절 (%)",{exact:true}).fill("9")
  await page.getByLabel("월",{exact:true}).uncheck()
  await page.getByRole("button",{name:"시뮬레이션 실행",exact:true}).click()
  await expect(page.getByRole("alert").filter({hasText:"실행하지 못했습니다."})).toBeFocused()
  expect(simulationRequests).toHaveLength(0)
  await page.getByLabel("고정 투자 금액 (USD)",{exact:true}).fill("600.00000001")
  await expect(page.getByLabel("손절 (%)",{exact:true})).toHaveValue("9")
  const run=async()=>{const response=page.waitForResponse(r=>r.url().endsWith("/api/research/simulations") && r.status()===201);await page.getByRole("button",{name:"시뮬레이션 실행",exact:true}).click();return(await response).json()}
  const first=await run()
  expect(first.request.strategy.risk.stop_loss.value).toBe("9")
  expect(first.request.strategy.position_sizing.notional).toBe("600.00000001")
  expect(first.request.strategy.session.weekdays).toEqual([1,2,3,4])
  expect(first.request.strategy.risk.take_profit).toEqual(definition.risk.take_profit)
  await page.getByLabel("손절 (%)",{exact:true}).fill("invalid")
  await page.getByLabel("고정 투자 금액 (USD)",{exact:true}).fill("700.00000001")
  await page.getByLabel("뉴욕 진입 시작 (HH:MM)").fill("09:45")
  await page.getByRole("button",{name:"시뮬레이션 실행",exact:true}).click()
  await expect(page.getByRole("alert").filter({hasText:"실행하지 못했습니다."})).toBeFocused()
  expect(simulationRequests).toHaveLength(1)
  await page.getByLabel("손절 (%)",{exact:true}).fill("8")
  await expect(page.getByLabel("고정 투자 금액 (USD)",{exact:true})).toHaveValue("700.00000001")
  await expect(page.getByLabel("뉴욕 진입 시작 (HH:MM)")).toHaveValue("09:45")
  const second=await run()
  expect(second.request.strategy.risk.stop_loss.value).toBe("8")
  expect(second.request.strategy.position_sizing.notional).toBe("700.00000001")
  expect(second.request.strategy.session).toEqual({...definition.session,entry_start:"09:45",weekdays:[1,2,3,4]})
  const current=JSON.parse(await page.getByLabel("고급 전략 JSON").inputValue())
  expect(current.entry).toEqual(definition.entry)
  expect(current.risk.take_profit).toEqual(definition.risk.take_profit)
  expect((simulationRequests[1] as {strategy:unknown}).strategy).toEqual(current)
  await page.screenshot({path:info.outputPath("multi-branch-repaired.png"),fullPage:true})
  await page.getByRole("button",{name:"보관함",exact:true}).click()
  const saveResponse=page.waitForResponse(r=>r.url().endsWith("/research/library/strategies") && r.status()===201)
  await page.getByRole("button",{name:"현재 전략 저장",exact:true}).click()
  const saved=await saveResponse
  expect(saved.request().postDataJSON().definition).toEqual(current)
  expect((await saved.json()).definition).toEqual(second.request.strategy)
  await page.getByRole("button",{name:"실험",exact:true}).click()
  const gridResponse=page.waitForResponse(r=>r.url().endsWith("/research/experiments/grid") && r.status()===201)
  await page.getByRole("button",{name:"Grid 실행",exact:true}).click()
  const grid=await gridResponse
  expect(grid.request().postDataJSON().base.strategy).toEqual(current)
  const experiment=await grid.json()
  expect(experiment.request.base.strategy).toEqual(second.request.strategy)
  expect(experiment.rows.map((row:{status:string})=>row.status)).toEqual(["succeeded","succeeded"])
  await expect(page.getByText("grid 결과",{exact:true})).toBeVisible()
  const metrics=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}))
  expect(metrics.scrollWidth).toBeLessThanOrEqual(metrics.width)
  console.log("ROUND2_LAYOUT",JSON.stringify(metrics));await info.attach("round2-layout",{body:JSON.stringify(metrics),contentType:"application/json"})
})
